#!/usr/bin/env python3
"""Build the twelve QR destinations from the collection's titles and audio URLs.

Run from any directory: python3 scripts/build_rauhnaechte_pages.py
No dependencies or runtime fetches are needed; GitHub Pages serves real HTML files.
"""

import html
import re
from pathlib import Path
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
COLLECTION = ROOT / "de" / "rauhnaechte"
BASE_URL = "https://nokmali.com/de/rauhnaechte/"


def replace_once(pattern, replacement, value):
    result, count = re.subn(pattern, lambda _: replacement, value, count=1, flags=re.S)
    if count != 1:
        raise ValueError(f"Collection markup no longer matches: {pattern}")
    return result


def build_pages():
    source = (COLLECTION / "index.html").read_text()
    rows = re.findall(r'<li class="meditation"(?=\s).*?</li>', source, re.S)
    numbers = [re.search(r'id="meditation-(\d{2})"', row).group(1) for row in rows]
    if numbers != [f"{number:02}" for number in range(1, 13)]:
        raise ValueError("The collection must contain entries 01–12 in order.")

    for number, row in zip(numbers, rows):
        title_match = re.search(r'<span class="track-title"([^>]*)>(.*?)</span>', row, re.S)
        title = html.unescape(title_match.group(2).strip())
        title_text = html.escape(title)
        language = re.search(r'lang="([^"]+)"', title_match.group(1))
        language_attr = f' lang="{html.escape(language.group(1), quote=True)}"' if language else ""
        audio_src = html.unescape(re.search(r'data-audio-src="([^"]*)"', row).group(1))
        # A relative source in the collection must resolve identically one folder deeper.
        if audio_src and not urlsplit(audio_src).scheme and not audio_src.startswith("/"):
            row = replace_once(r'data-audio-src="[^"]*"', f'data-audio-src="{html.escape("../" + audio_src, quote=True)}"', row)
        row = row.replace('<li class="meditation"', f'<li class="meditation" data-title="{html.escape(title, quote=True)}"', 1)
        row = replace_once(r'<span class="track-title"[^>]*>.*?</span>', '<span class="track-title">Meditation anhören</span>', row)
        if not audio_src:
            row = replace_once(r'<span class="track-status">.*?</span>', '<span class="track-status">Aufnahme folgt</span>', row)

        page_url = f"{BASE_URL}{number}/"
        page = source
        page = replace_once(r'<title>.*?</title>', f'<title>{title_text} · Rauhnächte {number} | Nokmali</title>', page)
        page = page.replace(f'content="{BASE_URL}"', f'content="{page_url}"')
        page = page.replace(f'href="{BASE_URL}"', f'href="{page_url}"')
        page = replace_once(r'<meta name="description"[^>]*>', f'<meta name="description" content="Meditation {number}: {html.escape(title, quote=True)}. Deine Begleitung zum Rauhnächte-Journal von Nokmali.">', page)
        page = replace_once(r'<meta property="og:title"[^>]*>', f'<meta property="og:title" content="{html.escape(title, quote=True)} · Rauhnächte {number} | Nokmali">', page)
        page = replace_once(r'<meta property="og:description"[^>]*>', f'<meta property="og:description" content="Meditation {number} zu deinem Rauhnächte-Journal. Ein Moment für dich.">', page)
        # HTML asset and homepage links need one extra parent; shared CSS URLs do not.
        page = page.replace('="../../', '="../../../')
        page = page.replace('href="../index.html"', 'href="../../index.html"')
        page = page.replace('="./meditation.', '="../meditation.')
        page = page.replace('<body>', f'<body data-recording="{number}">', 1)
        page = replace_once(r'<p class="eyebrow">.*?</p>', f'<p class="eyebrow">Deine Rauhnächte · Meditation {number}</p>', page)
        page = replace_once(r'<h1>.*?</h1>', f'<h1{language_attr}>{title_text}</h1>', page)
        page = replace_once(r'<p class="hero-copy">.*?</p>', '<p class="hero-copy">Ein Moment zum Ankommen, Spüren und Gestalten.<br class="desktop-break"> Nimm dir die Zeit, die du brauchst.</p>', page)
        page = replace_once(r'<div class="section-heading">.*?</div>', f'<a class="collection-link" href="../index.html"><span aria-hidden="true">←</span> Alle 12 Meditationen</a><h2 id="library-title" class="sr-only">Meditation {number} anhören</h2>', page)
        availability = "Tippe auf die Wiedergabetaste, um die Meditation anzuhören." if audio_src else "Diese Aufnahme entsteht gerade. Du findest sie später genau hier."
        page = replace_once(r'<p class="availability-note">.*?</p>', f'<p class="availability-note">{availability}</p>', page)
        page = replace_once(r'<!-- Keep these numbered IDs.*?-->', '<!-- Generated by scripts/build_rauhnaechte_pages.py. Edit the collection, then rebuild. -->', page)
        page = replace_once(r'<ol class="meditation-list">.*?</ol>', f'<ol class="meditation-list" start="{int(number)}">\n        {row}\n      </ol>', page)

        destination = COLLECTION / number
        destination.mkdir(exist_ok=True)
        (destination / "index.html").write_text(page)
        print(f"Built /de/rauhnaechte/{number}/ — {title}")


if __name__ == "__main__":
    build_pages()
